import { act, renderHook } from '@testing-library/react';
import { produce } from 'immer';
import { describe, expect, it, vi } from 'vitest';

import { storyEvent, storyMedia } from '@/.storybook/fixtures';
import { useInvitationEventSync } from '@/hooks/useInvitationEventSync';
import type { EventDetailResponseDto } from '@/lib/api/types';
import { createInvitationEditorStore } from '@/lib/invitation/editorStore';
import { SAMPLE_DOCUMENT } from '@/lib/invitation/samples';

const sources = vi.hoisted(() => ({
    event: undefined as EventDetailResponseDto | undefined,
    qrLinks: undefined as unknown,
    samples: null as ReadonlyMap<string, unknown> | null,
    themeSlug: undefined as string | null | undefined,
}));

vi.mock('@/hooks/useEvent', () => ({ useEvent: () => ({ data: sources.event }) }));
vi.mock('@/hooks/useQrLinks', () => ({ useEventQrLinks: () => ({ data: sources.qrLinks }) }));
vi.mock('@/hooks/useThemeSampleSections', () => ({
    useThemeSampleSections: (slug: string | null) => {
        sources.themeSlug = slug;
        return sources.samples;
    },
}));

const JOIN_LINK = { targetType: 'EVENT_JOIN', autoGenerated: true, status: 'ACTIVE', publicUrl: 'https://storywall.gr/q/tok' };

function linkedDocument() {
    return produce(SAMPLE_DOCUMENT, (draft) => {
        const date = draft.sections.find((section) => section.type === 'date');
        if (date) date.link = { source: 'event', enabled: true };
    });
}

function dateIso(store: ReturnType<typeof createInvitationEditorStore>) {
    const date = store.getState().document.sections.find((section) => section.type === 'date');
    return date?.type === 'date' ? date.data.iso : undefined;
}

describe('useInvitationEventSync', () => {
    it("writes the event into the linked sections outside the undo history, and follows the event's changes", () => {
        sources.event = storyEvent({ schedule: { ...storyEvent().schedule, startAt: '2027-07-12T15:30:00Z', timezone: 'Europe/Athens' } });
        sources.qrLinks = [JOIN_LINK];
        const store = createInvitationEditorStore(linkedDocument());
        const media = vi.fn(() => undefined);

        const { result, rerender } = renderHook(() => useInvitationEventSync(store, sources.event!.id, media, 'classic'));

        expect(dateIso(store)).toBe('2027-07-12T18:30');
        expect(store.getState().past).toHaveLength(0);
        expect(store.getState().changeCount).toBeGreaterThan(0);
        expect(result.current.joinUrl).toBe('https://storywall.gr/q/tok');

        sources.event = { ...sources.event, schedule: { ...sources.event.schedule, startAt: '2027-08-01T15:30:00Z' } };
        rerender();
        expect(dateIso(store)).toBe('2027-08-01T18:30');
    });

    it('stops following a field once the host edits it', () => {
        sources.event = storyEvent({ schedule: { ...storyEvent().schedule, startAt: '2027-07-12T15:30:00Z', timezone: 'Europe/Athens' } });
        const store = createInvitationEditorStore(linkedDocument());
        const { rerender } = renderHook(() => useInvitationEventSync(store, sources.event!.id, vi.fn(() => undefined), 'classic'));

        act(() =>
            store.getState().edit((draft) => {
                const date = draft.sections.find((section) => section.type === 'date');
                if (date?.type === 'date') date.data.iso = '2027-09-09T12:00';
            }),
        );
        sources.event = { ...sources.event, schedule: { ...sources.event.schedule, startAt: '2027-10-01T15:30:00Z' } };
        rerender();

        expect(dateIso(store)).toBe('2027-09-09T12:00');
    });

    it("draws the event's cover from the event's own detail when the draft has no URL for it", () => {
        sources.event = storyEvent({ coverMedia: storyMedia('cover-1', { mediaUrl: 'https://cdn.test/cover.jpg' }) });
        const store = createInvitationEditorStore(linkedDocument());
        const { result } = renderHook(() => useInvitationEventSync(store, sources.event!.id, (id) => (id === 'm-own' ? 'https://cdn.test/own.jpg' : undefined), 'classic'));

        expect(result.current.media('cover-1')).toBe('https://cdn.test/cover.jpg');
        expect(result.current.media('m-own')).toBe('https://cdn.test/own.jpg');
    });

    it('does nothing for a draft on no event', () => {
        sources.event = undefined;
        sources.qrLinks = undefined;
        const store = createInvitationEditorStore(linkedDocument());
        const { result } = renderHook(() => useInvitationEventSync(store, null, vi.fn(() => undefined), 'classic'));

        expect(result.current.event).toBeNull();
        expect(store.getState().changeCount).toBe(0);
        // No theme to fetch either.
        expect(sources.themeSlug).toBeNull();
    });

    it("links what still holds the theme's sample content once the theme is known", () => {
        sources.event = storyEvent({ schedule: { ...storyEvent().schedule, startAt: '2027-07-12T15:30:00Z', timezone: 'Europe/Athens' } });
        sources.samples = null;
        const store = createInvitationEditorStore(SAMPLE_DOCUMENT);
        const { rerender } = renderHook(() => useInvitationEventSync(store, sources.event!.id, vi.fn(() => undefined), 'classic'));

        expect(store.getState().document.sections.some((section) => section.link)).toBe(false);

        sources.samples = new Map(SAMPLE_DOCUMENT.sections.map((section) => [section.id, section]));
        rerender();
        expect(store.getState().document.sections.find((section) => section.type === 'date')?.link).toEqual({ source: 'event', enabled: true });
        expect(dateIso(store)).toBe('2027-07-12T18:30');
        sources.samples = null;
    });
});
