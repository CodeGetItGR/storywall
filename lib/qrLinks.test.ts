import { describe, expect, it } from 'vitest';

import type { EventModuleResponseDto, QrLinkResolutionDto, QrLinkResponseDto } from '@/lib/api/types';
import {
    findAutoInviteQrLink,
    findGuestQrLink,
    getQrRedirectPath,
    isGalleryOpenToGuests,
    isInvitationQrLink,
    isMemberArchiveEnabled,
} from '@/lib/qrLinks';

const active = (targetType: QrLinkResolutionDto['targetType'], inviteToken?: string): QrLinkResolutionDto => ({
    status: 'ACTIVE',
    targetType,
    inviteToken,
});

describe('getQrRedirectPath', () => {
    // The invite page shows the event first and then asks whether the guest has an account.
    it('sends a scanner of the join link to the invite page', () => {
        expect(getQrRedirectPath(active('EVENT_JOIN', 'tok'))).toBe('/invite/tok');
    });

    it('sends a personal invitation to the invite page', () => {
        expect(getQrRedirectPath(active('INVITATION', 'tok'))).toBe('/invite/tok');
    });

    it('does not redirect a gallery upload link, a link without a token, or one that is not active', () => {
        expect(getQrRedirectPath(active('MEDIA_UPLOAD'))).toBeNull();
        expect(getQrRedirectPath(active('EVENT_JOIN'))).toBeNull();
        expect(getQrRedirectPath({ ...active('EVENT_JOIN', 'tok'), status: 'REVOKED' })).toBeNull();
        expect(getQrRedirectPath(undefined)).toBeNull();
    });
});

function gallery(isAvailable: boolean, configuration: Record<string, unknown> | null): EventModuleResponseDto[] {
    return [{ moduleKey: 'gallery', isAvailable, configuration } as EventModuleResponseDto];
}

describe('isMemberArchiveEnabled', () => {
    it('is on only when the gallery is available and the flag is exactly true', () => {
        expect(isMemberArchiveEnabled(gallery(true, { qrUploadEnabled: true, memberArchiveAfterEnd: true }))).toBe(true);
        expect(isMemberArchiveEnabled(gallery(false, { memberArchiveAfterEnd: true }))).toBe(false);
        expect(isMemberArchiveEnabled(gallery(true, { qrUploadEnabled: true }))).toBe(false);
        expect(isMemberArchiveEnabled(gallery(true, { memberArchiveAfterEnd: 'true' }))).toBe(false);
        expect(isMemberArchiveEnabled(gallery(true, null))).toBe(false);
        expect(isMemberArchiveEnabled(undefined)).toBe(false);
    });
});

describe('isGalleryOpenToGuests', () => {
    const withArchive = gallery(true, { memberArchiveAfterEnd: true });

    it('opens the gallery to guests only where members get the download', () => {
        expect(isGalleryOpenToGuests({ deletedAt: null, modules: withArchive })).toBe(true);
        expect(isGalleryOpenToGuests({ deletedAt: null, modules: gallery(true, { qrUploadEnabled: true }) })).toBe(false);
        expect(isGalleryOpenToGuests({ deletedAt: null, modules: gallery(false, { memberArchiveAfterEnd: true }) })).toBe(false);
    });

    it('keeps it closed on a suspended or deleted event, and before the event loads', () => {
        expect(isGalleryOpenToGuests({ deletedAt: null, suspended: true, modules: withArchive })).toBe(false);
        expect(isGalleryOpenToGuests({ deletedAt: '2026-10-01T00:00:00Z', modules: gallery(false, { memberArchiveAfterEnd: true }) })).toBe(false);
        expect(isGalleryOpenToGuests(null)).toBe(false);
    });
});

describe('findAutoInviteQrLink', () => {
    const link = (overrides: Partial<QrLinkResponseDto>) =>
        ({ targetType: 'EVENT_JOIN', autoGenerated: true, status: 'ACTIVE', ...overrides }) as QrLinkResponseDto;

    it('returns the active auto-generated join link', () => {
        const invite = link({ id: 'auto' });
        expect(findAutoInviteQrLink([link({ id: 'manual', autoGenerated: false }), invite])).toBe(invite);
    });

    it('ignores revoked, gallery and host-made links', () => {
        expect(findAutoInviteQrLink([link({ status: 'REVOKED' }), link({ targetType: 'MEDIA_UPLOAD' }), link({ autoGenerated: false })])).toBeNull();
    });
});

describe('findGuestQrLink', () => {
    it('finds the guest code while it is not revoked', () => {
        const guest = { id: 'g', targetType: 'GUEST', status: 'ACTIVE' } as QrLinkResponseDto;
        const join = { id: 'j', targetType: 'EVENT_JOIN', status: 'ACTIVE' } as QrLinkResponseDto;
        expect(findGuestQrLink([join, guest])).toBe(guest);
        expect(findGuestQrLink([{ ...guest, status: 'REVOKED' }])).toBeNull();
        expect(findGuestQrLink([join])).toBeNull();
    });
});

describe('isInvitationQrLink', () => {
    // The gallery upload code and the guest code bring no one into the event.
    it('counts join links and personal invitations only', () => {
        const link = (targetType: QrLinkResponseDto['targetType']) => ({ id: targetType, targetType, status: 'ACTIVE' }) as QrLinkResponseDto;
        expect(isInvitationQrLink(link('EVENT_JOIN'))).toBe(true);
        expect(isInvitationQrLink(link('INVITATION'))).toBe(true);
        expect(isInvitationQrLink(link('MEDIA_UPLOAD'))).toBe(false);
        expect(isInvitationQrLink(link('GUEST'))).toBe(false);
    });
});
